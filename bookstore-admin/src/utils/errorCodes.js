/**
 * 根据后端返回的错误码获取友好提示
 * @param {number|string} code 业务错误码
 * @param {string} fallbackMsg 后端返回的原始消息（兜底用）
 * @returns {string} 友好提示文案
 */
export function getErrorMessage(code, fallbackMsg) {
  // 优先查映射表
  if (errorCodes[code]) {
    return errorCodes[code]
  }
  // 兜底：用后端返回的 msg
  if (fallbackMsg) {
    return fallbackMsg
  }
  return '请求失败，请稍后重试'
}

export default errorCodes
